import { toTsType, type JsonSchema } from "./jsonSchema";

/**
 * Turns the OpenAPI document into the typed client's source (G1.06): one entry per operation with its method, path, parameters,
 * request body and response, as TypeScript types. The hand-written runtime (`src/api-client/client.ts`) turns that table into
 * `client.listLeads({ params, query, body })` with the error envelope handled in one place.
 *
 * Pure and deterministic: the same document always produces the same text, so a CI check can compare it with the committed file.
 */

interface OperationInfo {
  id: string;
  method: string;
  path: string;
  tag: string;
  summary: string;
  pathParams: string[];
  query: JsonSchema | null;
  body: JsonSchema | null;
  response: JsonSchema | null;
  errors: number[];
  contentType: "json" | "csv" | "multipart" | "none";
  access: string[] | null;
}

function collect(doc: any): OperationInfo[] {
  const out: OperationInfo[] = [];
  for (const [path, item] of Object.entries<any>(doc.paths ?? {})) {
    for (const [method, op] of Object.entries<any>(item)) {
      const params: any[] = op.parameters ?? [];
      const queryProps: Record<string, JsonSchema> = {};
      const required: string[] = [];
      for (const p of params) {
        if (p.in === "query") {
          queryProps[p.name] = p.schema ?? {};
          if (p.required) required.push(p.name);
        }
      }
      const success = Object.entries<any>(op.responses ?? {}).find(([status]) => status.startsWith("2"));
      const content = success?.[1]?.content ?? {};
      const response = content["application/json"]?.schema ?? null;
      const bodyContent = op.requestBody?.content ?? {};
      out.push({
        id: op.operationId,
        method: method.toUpperCase(),
        path,
        tag: op.tags?.[0] ?? "Other",
        summary: String(op.summary ?? "").replace(/\s+/g, " ").trim(),
        pathParams: [...path.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]!),
        query: Object.keys(queryProps).length ? { type: "object", properties: queryProps, required, additionalProperties: false } : null,
        body: bodyContent["application/json"]?.schema ?? null,
        response,
        errors: Object.keys(op.responses ?? {}).map(Number).filter((n) => n >= 400 && n !== 500),
        contentType: bodyContent["multipart/form-data"] ? "multipart" : content["text/csv"] ? "csv" : response ? "json" : "none",
        access: Array.isArray(op["x-allowed-roles"]) ? op["x-allowed-roles"] : null,
      });
    }
  }
  return out.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

export function buildClientSource(doc: any): string {
  const ops = collect(doc);
  const schemas: Record<string, JsonSchema> = doc.components?.schemas ?? {};
  const lines: string[] = [];
  lines.push("/* eslint-disable */");
  lines.push("// GENERATED by scripts/generate-api-client.ts from the OpenAPI document. Do not edit by hand.");
  lines.push(`// Contract: ${doc.info?.title ?? "API"} ${doc.info?.version ?? ""}`.trimEnd());
  lines.push("");
  lines.push("export interface Schemas {");
  for (const [name, schema] of Object.entries(schemas)) lines.push(`  ${JSON.stringify(name)}: ${toTsType(schema, doc, 1)};`);
  lines.push("}");
  lines.push("");
  lines.push("export interface Operations {");
  for (const op of ops) {
    const params = op.pathParams.length ? `{ ${op.pathParams.map((p) => `${p}: string`).join("; ")} }` : "Record<string, never>";
    lines.push(`  ${op.id}: {`);
    lines.push(`    params: ${params};`);
    lines.push(`    query: ${op.query ? toTsType(op.query, doc, 2) : "undefined"};`);
    lines.push(`    body: ${op.body ? toTsType(op.body, doc, 2) : op.contentType === "multipart" ? "FormData" : "undefined"};`);
    lines.push(`    response: ${op.contentType === "csv" ? "string" : op.response ? toTsType(op.response, doc, 2) : "void"};`);
    lines.push("  };");
  }
  lines.push("}");
  lines.push("");
  lines.push("export type OperationId = keyof Operations;");
  lines.push("");
  lines.push("export const operations = {");
  for (const op of ops) {
    lines.push(
      `  ${op.id}: { method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)}, tag: ${JSON.stringify(op.tag)}, summary: ${JSON.stringify(op.summary)}, contentType: ${JSON.stringify(op.contentType)}, errors: ${JSON.stringify(op.errors)}, allowedRoles: ${JSON.stringify(op.access)} },`,
    );
  }
  lines.push("} as const;");
  lines.push("");
  return lines.join("\n");
}
